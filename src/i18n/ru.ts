/** Plural object keys, shared with the DeepPartial helper below. */
type Plural = { one: string; few: string; many: string; other: string }

/** Nested partial: optional sections AND optional keys inside sections. */
export type DeepPartial<T> = {
  [K in keyof T]?: T[K] extends Plural
    ? Partial<Plural>
    : T[K] extends object
      ? DeepPartial<T[K]>
      : T[K]
}
